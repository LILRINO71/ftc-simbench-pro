// Writes src/autorig-lib.js from the research prototypes in research/autorig,
// so the app runs exactly the code the study measured. Each ES module becomes
// its own scope (no imports, exports returned), in the plain-script form every
// src/ file has.   node tools/gen-autorig.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const R = (p) => fs.readFileSync(path.join(ROOT, 'research', 'autorig', p), 'utf8');
const wrap = (src, names) => {
  if (/^\s*import\s/m.test(src)) throw new Error('a prototype imports something; the generator only handles self-contained modules');
  return '(function(){\n' + src.replace(/^export\s+/gm, '') + '\nreturn {' + names.join(', ') + '};\n})()';
};
const out = `/* ============================================================
   AUTORIG LIBRARY — generated by tools/gen-autorig.mjs from
   research/autorig (actuators, slides, carry). Do not edit here: change
   the prototype, re-run its eval, then regenerate. src/autorig.js puts
   the three together into a joint spec.
   ============================================================ */
const ARActuators=${wrap(R('actuators/actuators.mjs'), ['findActuators'])};
const ARSlides=${wrap(R('slides/slides.mjs'), ['findSlides', 'toJointSpec', 'SLIDE_DEFAULTS'])};
const ARCarry=${wrap(R('carry/carry.mjs'), ['inferCarry', 'contactGraph', 'railness'])};
`;
fs.writeFileSync(path.join(ROOT, 'src', 'autorig-lib.js'), out.replace(/\r\n/g, '\n'), 'utf8');
console.log('src/autorig-lib.js', (out.length / 1024).toFixed(0) + ' KB');
