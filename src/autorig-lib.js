    nn = mul(nn, 1 / L); let dd = dot(nn, P[i]);
    if (dot(nn, inside) - dd > 0) { const t = j; j = k; k = t; nn = mul(nn, -1); dd = -dd; }
    faces.push({ v: [i, j, k], n: nn, d: dd, alive: true });
